CREATE TABLE materias (
    id_materia       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_materia   VARCHAR(100) NOT NULL UNIQUE,
    creditos         INTEGER      NOT NULL CHECK (creditos > 0),
    nivel_prioridad  SMALLINT     NOT NULL CHECK (nivel_prioridad IN (1, 2, 3)),
    descripcion      TEXT         NULL,
    activa           BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE componentes (
    id_componente        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_materia           INTEGER      NOT NULL REFERENCES materias (id_materia)
                                      ON UPDATE CASCADE ON DELETE RESTRICT,
    nombre_componente    VARCHAR(100) NOT NULL,
    descripcion          TEXT         NULL,
    preguntas_por_examen SMALLINT     NOT NULL DEFAULT 10 CHECK (preguntas_por_examen > 0),
    CONSTRAINT uq_componente UNIQUE (id_materia, nombre_componente)
);

CREATE TABLE nivel_dificultad (
    id_nivel      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_nivel  VARCHAR(30)  NOT NULL UNIQUE,
    descripcion   TEXT         NULL,
    peso          NUMERIC(3,1) NOT NULL DEFAULT 1.0 CHECK (peso > 0)
);

CREATE TABLE preguntas (
    id_pregunta     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_componente   INTEGER   NOT NULL REFERENCES componentes (id_componente)
                              ON UPDATE CASCADE ON DELETE RESTRICT,
    id_nivel        INTEGER   NOT NULL REFERENCES nivel_dificultad (id_nivel)
                              ON UPDATE CASCADE ON DELETE RESTRICT,
    enunciado       TEXT      NOT NULL UNIQUE,
    activa          BOOLEAN   NOT NULL DEFAULT TRUE,
    fecha_creacion  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE opciones_respuesta (
    id_opcion    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pregunta  INTEGER NOT NULL REFERENCES preguntas (id_pregunta)
                         ON UPDATE CASCADE ON DELETE CASCADE,
    letra        CHAR(1) NOT NULL CHECK (letra IN ('A', 'B', 'C', 'D')),
    texto        VARCHAR(255) NOT NULL,
    es_correcta  BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_opcion_letra UNIQUE (id_pregunta, letra),
    CONSTRAINT uq_opcion_texto UNIQUE (id_pregunta, texto),
    CONSTRAINT uq_opcion_pregunta UNIQUE (id_opcion, id_pregunta)
);
CREATE UNIQUE INDEX uq_una_correcta_por_pregunta
    ON opciones_respuesta (id_pregunta) WHERE es_correcta;

CREATE TABLE estudiantes (
    id_estudiante   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento       VARCHAR(20)  NOT NULL UNIQUE CHECK (documento ~ '^[0-9]{5,20}$'),
    nombres         VARCHAR(80)  NOT NULL,
    apellidos       VARCHAR(80)  NOT NULL,
    correo          VARCHAR(120) NULL UNIQUE,
    programa        VARCHAR(120) NULL,
    semestre        SMALLINT     NULL CHECK (semestre BETWEEN 1 AND 12),
    fecha_registro  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE examenes (
    id_examen        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudiante    INTEGER     NOT NULL REFERENCES estudiantes (id_estudiante)
                                 ON UPDATE CASCADE ON DELETE RESTRICT,
    id_materia       INTEGER     NOT NULL REFERENCES materias (id_materia)
                                 ON UPDATE CASCADE ON DELETE RESTRICT,
    fecha_inicio     TIMESTAMPTZ NOT NULL DEFAULT now(),
    fecha_fin        TIMESTAMPTZ NULL,
    tiempo_segundos  INTEGER     NULL CHECK (tiempo_segundos >= 0),
    puntaje_total    SMALLINT    NULL CHECK (puntaje_total BETWEEN 0 AND 30),
    total_preguntas  SMALLINT    NOT NULL DEFAULT 30,
    estado           VARCHAR(12) NOT NULL DEFAULT 'EN_CURSO'
                     CHECK (estado IN ('EN_CURSO', 'FINALIZADO', 'ANULADO')),
    CONSTRAINT ck_fechas CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

CREATE TABLE detalle_examen (
    id_detalle              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_examen               INTEGER  NOT NULL REFERENCES examenes (id_examen)
                                     ON UPDATE CASCADE ON DELETE CASCADE,
    id_pregunta             INTEGER  NOT NULL REFERENCES preguntas (id_pregunta)
                                     ON UPDATE CASCADE ON DELETE RESTRICT,
    orden                   SMALLINT NOT NULL CHECK (orden BETWEEN 1 AND 30),
    id_opcion_seleccionada  INTEGER  NULL,
    es_correcta             BOOLEAN  NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_detalle_opcion FOREIGN KEY (id_opcion_seleccionada, id_pregunta)
        REFERENCES opciones_respuesta (id_opcion, id_pregunta) ON DELETE RESTRICT,
    CONSTRAINT uq_detalle_pregunta UNIQUE (id_examen, id_pregunta),
    CONSTRAINT uq_detalle_orden    UNIQUE (id_examen, orden)
);

CREATE TABLE resultados_componente (
    id_resultado     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_examen        INTEGER      NOT NULL REFERENCES examenes (id_examen)
                                  ON UPDATE CASCADE ON DELETE CASCADE,
    id_componente    INTEGER      NOT NULL REFERENCES componentes (id_componente)
                                  ON UPDATE CASCADE ON DELETE RESTRICT,
    aciertos         SMALLINT     NOT NULL CHECK (aciertos >= 0),
    total_preguntas  SMALLINT     NOT NULL CHECK (total_preguntas > 0),
    porcentaje       NUMERIC(5,1) NOT NULL CHECK (porcentaje BETWEEN 0 AND 100),
    CONSTRAINT uq_resultado UNIQUE (id_examen, id_componente),
    CONSTRAINT ck_aciertos CHECK (aciertos <= total_preguntas)
);

CREATE TABLE diagnosticos_ia (
    id_diagnostico     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_examen          INTEGER      NOT NULL UNIQUE REFERENCES examenes (id_examen)
                                    ON UPDATE CASCADE ON DELETE CASCADE,
    fortalezas         TEXT         NOT NULL,
    debilidades        TEXT         NOT NULL,
    plan_estudio       TEXT         NOT NULL,
    resumen_enviado    JSONB        NOT NULL,
    modelo_ia          VARCHAR(60)  NOT NULL,
    tiempo_respuesta_s NUMERIC(6,2) NULL,
    fecha_generacion   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_preguntas_componente ON preguntas (id_componente) WHERE activa;
CREATE INDEX idx_preguntas_nivel      ON preguntas (id_nivel);
CREATE INDEX idx_opciones_pregunta    ON opciones_respuesta (id_pregunta);
CREATE INDEX idx_examenes_estudiante  ON examenes (id_estudiante, fecha_inicio DESC);
CREATE INDEX idx_detalle_examen       ON detalle_examen (id_examen);

CREATE VIEW vw_banco_por_componente AS
SELECT m.nombre_materia, c.nombre_componente, n.nombre_nivel,
       COUNT(p.id_pregunta) AS total_preguntas
FROM preguntas p
JOIN componentes c      ON c.id_componente = p.id_componente
JOIN materias m         ON m.id_materia    = c.id_materia
JOIN nivel_dificultad n ON n.id_nivel      = p.id_nivel
WHERE p.activa
GROUP BY m.nombre_materia, c.nombre_componente, n.nombre_nivel;

CREATE VIEW vw_historial_estudiante AS
SELECT e.id_examen, s.documento, s.nombres || ' ' || s.apellidos AS estudiante,
       e.fecha_inicio, e.tiempo_segundos, e.puntaje_total, e.estado,
       ROUND(e.puntaje_total * 100.0 / e.total_preguntas, 1) AS porcentaje_global
FROM examenes e
JOIN estudiantes s ON s.id_estudiante = e.id_estudiante;
